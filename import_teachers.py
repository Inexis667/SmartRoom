def load_teachers():
    with get_connection() as db:
        # Очищаем таблицу преподавателей
        db.execute("DELETE FROM teachers")

        # Загружаем чистый список
        for name in TEACHERS_LIST:
            try:
                db.execute("INSERT INTO teachers (full_name) VALUES (?)", (name,))
            except sqlite3.IntegrityError:
                pass  # Пропускаем, если вдруг уже есть

    print(f"Успешно загружено {len(TEACHERS_LIST)} преподавателей!")


